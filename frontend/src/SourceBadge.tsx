import type { GenerationSource } from "./generationSource";

/** 差分（提案）の確認画面に出す、生成元の表示。モックと実接続を、文字で区別する（色だけに頼らない）。 */
export function SourceBadge({ source }: { source: GenerationSource }) {
  if (source.kind === "template") {
    return <p className="source-badge" data-testid="source-badge" data-source="template">Source: Saved request (no Bedrock call)</p>;
  }
  return source.kind === "bedrock" ? (
    <p className="source-badge source-bedrock" data-testid="source-badge" data-source="bedrock">
      <strong>Source: Amazon Bedrock (live connection)</strong>
      <span className="source-detail"> Model: {source.modelId} / Region: {source.region}</span>
    </p>
  ) : (
    <p className="source-badge source-mock" data-testid="source-badge" data-source="mock">
      <strong>Source: Mock (simulated)</strong>
      <span className="source-detail"> A simulated response generated from fixed rules (not a real AI)</span>
    </p>
  );
}

/**
 * 画面の説明の、AIの部分。生成元がまだ分からないとき（一覧の読み込み前・失敗）は null。
 * failed は、一覧の取得に失敗したとき（読み込み中のまま、と誤解させない）。
 */
export function AiNote({ source, failed = false }: { source: GenerationSource | null; failed?: boolean }) {
  if (source === null) {
    return failed ? <>Could not determine the AI source (the list could not be retrieved).</> : <>Checking the AI source…</>;
  }
  if (source.kind === "bedrock") {
    return (
      <>
        <strong>Live connection (Amazon Bedrock).</strong> AI responses are generated by Amazon Bedrock (model: {source.modelId}, region: {source.region}).
        Each request incurs usage charges. The app validates the AI output and applies nothing until you choose Yes.
      </>
    );
  }
  return (
    <>
      <strong>This is a mock.</strong> AI responses are simulated from fixed rules; no real AI is connected.
    </>
  );
}
